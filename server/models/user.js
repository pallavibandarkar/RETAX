import mongoose from "mongoose";

const userSchema = new mongoose.Schema({
  email: {
    type: String,
    required: true,
    unique: true,
  },
  name: {
    type: String,
    required: true,
  },
  password: {
    type: String,
    required: true,
  },
  role: {
    type: String,
    enum: ["admin", "team admin", "sales", "support", "other"],
    required: true,
  },
  createdAt: {
    type: Date,
    default: Date.now,
  },
  isActive: {
    type: Boolean,
    default: true,
  },
  teams: [
    {
      type: mongoose.Schema.ObjectId,
      ref: "TeamSpace",
    },
  ],
});

const User = mongoose.model("User", userSchema);

export default User;
